def main() -> None:
    for name, (title, rows) in XLSX.items():
        (ROOT / name).mkdir(exist_ok=True)
        xlsx(ROOT / name / "spec.xlsx", title, rows)
    for name, paragraphs in DOCX.items():
        (ROOT / name).mkdir(exist_ok=True)
        docx_file(ROOT / name / "spec.docx", paragraphs)
    for name, text in MD.items():
        (ROOT / name).mkdir(exist_ok=True)
        (ROOT / name / "spec.md").write_text(text, encoding="utf-8")
    print("Готово:", ", ".join(str(p.relative_to(ROOT)) for p in sorted(ROOT.glob("*/spec.*"))))


if __name__ == "__main__":
    main()
