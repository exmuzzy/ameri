def xlsx(path: Path, title: str, rows: list[tuple]) -> None:
    book = openpyxl.Workbook()
    sheet = book.active
    sheet.title = "Спецификация"
    sheet.append([title])
    sheet.append(GOST_HEADER)
    for row in rows:
        sheet.append(list(row))
    sheet.column_dimensions["B"].width = 55
    sheet.column_dimensions["C"].width = 28
    props = book.properties
    props.creator = props.lastModifiedBy = props.title = ""
    props.created = props.modified = FIXED_DATE
    book.save(path)


def docx_file(path: Path, paragraphs: list[str]) -> None:
    document = docx.Document()
    for text in paragraphs:
        document.add_paragraph(text)
    core = document.core_properties
    for field in ("author", "last_modified_by", "title", "subject", "keywords", "comments", "category"):
        setattr(core, field, "")
    core.created = core.modified = FIXED_DATE
    core.revision = 1
    document.save(path)



